out = []
for u in new:
    k = key(u)
    if k in old_id:
        e = dict(tr[old_id[k]])
        if old_id[k] in DROP_NOTE:
            e.pop('note', None)
    else:
        e = dict(MANUAL[u['id']])
    ja = e['ja']
    for a, b in NORM:
        ja = ja.replace(a, b)
    rec = {'id': u['id'], 'vol': u['vol'], 'parts': [[p[0], p[1]] for p in u['parts']], 'ja': ja}
    for f in ('heading', 'sub', 'note', 'board'):
        if e.get(f):
            rec[f] = e[f]
    if u['id'] in SUB:
        rec.pop('heading', None)
        rec['sub'] = True
    if u['id'] in KEEP_ORIG:
        reps, note = KEEP_ORIG[u['id']]
        for a, b in reps:
            assert a in rec['ja'], (u['id'], a)
            rec['ja'] = rec['ja'].replace(a, b)
        if note:
            rec['note'] = note
    for a, b in NOTE_FIX.get(u['id'], []):
        assert a in rec['note'], (u['id'], a)
        rec['note'] = rec['note'].replace(a, b)
    if rec.get('note'):
        for a, b in NOTE_WORD:
            rec['note'] = rec['note'].replace(a, b)
        assert '誤り' not in rec['note'] and '誤記' not in rec['note'], (u['id'], rec['note'])
    out.append(rec)
