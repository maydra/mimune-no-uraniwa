    new_html_verses = ""
    
    for line in lines:
        line = line.strip()
        if not line: continue
        
        # Match "1 Text..." or "10 Text..."
        match = re.match(r'^(\d+)\s*(.*)', line)
        if match:
            v_num = match.group(1)
            v_text = match.group(2)
            
            # Reconstruct HTML format:
            # <p id="v1"><sup><a href="#v1" class="verse-link">1</a></sup>Text...</p>
            
            # Special handing for "キリスト" span links if any (The user provided text included MD links like [キリスト](...))
            # We should strip MD links or convert them.
            # The user's text from search result has [Text](URL).
            # We want to convert `[Text](URL)` to `<span class="keyword_link">Text</span>` or just `Text`.
            # Looking at existing 001.html, keywords are spans.
            # E.g. <span class="keyword_link">キリスト</span>
            
            # Check if text has markdown links
            def replace_md_link(m):
                text = m.group(1)
                return f'<span class="keyword_link">{text}</span>'
            
            v_text = re.sub(r'\[([^\]]+)\]\([^)]+\)', replace_md_link, v_text)
            
            paragraph = f'<p id="v{v_num}"><sup><a href="#v{v_num}" class="verse-link">{v_num}</a></sup>{v_text}</p>\n'
            new_html_verses += paragraph
        else:
            # Fallback if line doesn't start with number (continuation?)
            # Just append to previous? Or wrap?
            pass

    # Now replace the block in original content
    # Look for <div class="the-post-cont"> ... </div>
    pattern = re.compile(r'(<div class="the-post-cont">\s*).*?(</div>)', re.DOTALL)
    
    if pattern.search(content):
        # We need to make sure we don't accidentally delete the div tags
        new_content = pattern.sub(f'\\1\n\n{new_html_verses}\n\\2', content)
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(new_content)
        print("  Updated successfully.")
    else:
        print("  Could not find target div in HTML.")

